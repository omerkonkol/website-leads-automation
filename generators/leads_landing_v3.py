def _infer_category(name: str | None) -> str | None:
    if not name: return None
    n = name.lower()
    for kw, cat in _NAME_KEYWORDS:
        if kw.lower() in n: return cat
    return None


_FINAL_HEB = str.maketrans("ךםןףץ", "כמנפצ")
def _norm_heb(s: str) -> str:
    """Normalize Hebrew final letters so plural/construct forms match dict keys."""
    return s.translate(_FINAL_HEB)

def _match(d: dict, category: str | None, default):
    if category:
        cat = category.strip()
        cat_n = _norm_heb(cat)
        # 1. Key is substring of category (normalized)
        for k, v in d.items():
            k_n = _norm_heb(k)
            if k_n in cat_n: return v
        # 2. Category is substring of key (normalized)
        for k, v in d.items():
            k_n = _norm_heb(k)
            if cat_n in k_n: return v
        # 3. Shared first word
        first = cat_n.split()[0] if cat_n.split() else cat_n
        for k, v in d.items():
            if _norm_heb(k).startswith(first): return v
    return default

def _wa_number(phone: str) -> str:
    digits = re.sub(r"\D", "", phone)
    if digits.startswith("0"): digits = "972" + digits[1:]
    return digits

def _slug(name: str, lead_id: int) -> str:
    s = unicodedata.normalize("NFKD", name)
    s = s.encode("ascii", "ignore").decode("ascii").lower()
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    s = re.sub(r"-+", "-", s)
    return f"{s}-{lead_id}" if s else str(lead_id)

def _strip_credentials(name: str) -> str:
    return re.sub(r"\s*\([^)]+\)\s*$", "", name).strip()

def _services_from_db(raw: str | None, fallback: list) -> list:
    if not raw: return fallback
    try: items = json.loads(raw)
    except Exception: return fallback
    if not isinstance(items, list) or not items: return fallback
    out = []
    for i, name in enumerate(items[:4]):
        if not isinstance(name, str) or not name.strip(): continue
        base = fallback[i] if i < len(fallback) else fallback[0]
        out.append({**base, "title": name.strip()})
    return out or fallback

def _hours_from_db(raw: str | None) -> list[tuple[str, str]]:
    if not raw: return []
    try: h = json.loads(raw)
    except Exception: return []
    if not isinstance(h, dict): return []
    order = ["sunday","monday","tuesday","wednesday","thursday","friday","saturday"]
    out = []
    for d in order:
        v = h.get(d)
        if isinstance(v, str):
            out.append((DAY_HE[d], _format_hours(v)))
    return out

def _format_hours(raw: str) -> str:
    if not raw: return ""
    t = re.sub(r"[  ]", " ", raw).strip()
    low = t.lower()
    if "closed" in low or "סגור" in t: return "סגור"
    if "open 24" in low or "24 hours" in low or "24/7" in low: return "24 שעות"
    m = re.match(r"(.+?)\s*[–\-—]\s*(.+)", t)
    if m:
        a, b = _parse_time(m.group(1)), _parse_time(m.group(2))
        if a and b: return f"{a}–{b}"
    return re.sub(r"\s*(am|pm)\s*", "", t, flags=re.I).strip()

def _parse_time(t: str) -> str:
    t = t.strip().lower()
    is_am, is_pm = "am" in t, "pm" in t
    t = re.sub(r"\s*(am|pm)\s*", "", t).strip()
    m = re.match(r"(\d{1,2})(?::(\d{2}))?", t)
    if not m: return t
    hour, minute = int(m.group(1)), m.group(2) or "00"
    if is_pm and hour < 12: hour += 12
    if is_am and hour == 12: hour = 0
    return f"{hour:02d}:{minute}"

def _pick_testimonials(lead: Lead, n: int = 5) -> list[tuple[str, str, str]]:
    rng = random.Random(lead.id * 7919 + 1)
    names = rng.sample(TESTIMONIAL_NAMES, n)
    cat_pool = _match(TESTIMONIAL_TEMPLATES_BY_CATEGORY, lead.category, [])
    quotes = []
    age_phrases = ["לפני שבוע","לפני שבועיים","לפני 3 שבועות","לפני חודש","לפני חודשיים","לפני 4 חודשים"]
    for _ in range(n):
        if cat_pool and rng.random() < 0.7:
            quotes.append(rng.choice(cat_pool))
        else:
            quotes.append(rng.choice(TESTIMONIAL_TEMPLATES_GENERIC))
    ages = (rng.sample(age_phrases, min(n, len(age_phrases))) + [age_phrases[0]] * max(0, n - len(age_phrases)))
    return list(zip(names, quotes, ages))


